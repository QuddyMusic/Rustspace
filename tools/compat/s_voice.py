import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from scn import run
def voice(c):
    a=c.user('al'); b=c.user('bo'); d=c.user('ca')
    sp=c.call('al','POST','/api/spaces',{'name':'Г','avatarColor':'sky'}); sid=sp['id']
    c.call('bo','POST','/api/spaces/join',{'inviteCode':sp['inviteCode']}); c.settle()
    full=c.call('al','GET',f'/api/spaces/{sid}')
    v1=[x for x in full['channels'] if x['type']=='voice'][0]['id']
    gen=[x for x in full['channels'] if x['type']=='text'][0]['id']
    v2=c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'v2','type':'voice'})['id']; c.settle()
    c.call('bo','POST','/api/livekit/token',{}, label='token-empty')
    c.call('bo','POST','/api/livekit/token',{'channelId':'nope'}, label='token-nochan')
    c.call('ca','POST','/api/livekit/token',{'channelId':v1}, label='token-nonmember')
    c.send('bo',{'type':'voice_join'}); c.settle()
    c.send('bo',{'type':'voice_join','channelId':'nope'}); c.settle()
    c.send('ca',{'type':'voice_join','channelId':v1}); c.settle()
    c.send('bo',{'type':'voice_status','isMuted':True}); c.settle()
    c.send('bo',{'type':'voice_join','channelId':v1}); c.settle()
    c.send('bo',{'type':'voice_status','isMuted':True,'isCameraOn':True}); c.settle()
    c.send('bo',{'type':'voice_join','channelId':v1}); c.settle()
    c.send('al',{'type':'voice_join','channelId':v1}); c.settle()
    c.send('bo',{'type':'voice_space_mute','userId':a,'muted':True}); c.settle()
    c.send('al',{'type':'voice_space_mute'}); c.settle()
    c.send('al',{'type':'voice_space_mute','userId':d,'muted':True}); c.settle()
    c.send('al',{'type':'voice_space_mute','userId':a,'muted':True}); c.settle()
    c.send('al',{'type':'voice_space_mute','userId':b,'muted':True}); c.settle()
    c.send('bo',{'type':'voice_status','isMuted':False}); c.settle()
    c.send('al',{'type':'voice_space_deafen','userId':b,'deafened':True}); c.settle()
    c.send('al',{'type':'voice_move','userId':b}); c.settle()
    c.send('al',{'type':'voice_move','userId':b,'targetChannelId':gen}); c.settle()
    c.send('al',{'type':'voice_move','userId':b,'targetChannelId':v1}); c.settle()
    c.send('al',{'type':'voice_move','userId':b,'targetChannelId':v2}); c.settle()
    c.send('al',{'type':'voice_space_mute','userId':b,'muted':False}); c.settle()
    c.send('al',{'type':'voice_space_deafen','userId':b,'deafened':False}); c.settle()
    c.send('al',{'type':'voice_disconnect','userId':a}); c.settle()
    c.send('bo',{'type':'voice_disconnect','userId':a}); c.settle()
    c.send('al',{'type':'voice_disconnect','userId':b}); c.settle()
    c.send('al',{'type':'voice_join','channelId':v2}); c.settle()
    c.send('al',{'type':'voice_leave'}); c.settle()
    c.send('al',{'type':'voice_leave'}); c.settle()
    # звонки
    dmc=c.call('al','POST','/api/dm',{'userId':b}); did=dmc['id']
    c.call('al','POST','/api/livekit/token',{'dmChannelId':'nope'}, label='token-dm-nonmember')
    c.send('al',{'type':'dm_call_start'}); c.settle()
    c.send('ca',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('al',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('al',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'dm_call_reject','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'dm_call_accept','dmChannelId':did}); c.settle()
    c.send('al',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'dm_call_accept','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'voice_status','isMuted':True}); c.settle()
    c.send('al',{'type':'dm_call_end','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('al',{'type':'dm_call_start','dmChannelId':did}); c.settle()
    c.send('al',{'type':'voice_leave'}); c.settle()
    c.send('bo',{'type':'voice_leave'}); c.settle()
    c.send('bo',{'type':'dm_call_accept'}); c.settle()
if __name__=='__main__': sys.exit(1 if run(voice, show='-v' in sys.argv) else 0)
