import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from scn import run
def channels(c):
    a=c.user('al'); b=c.user('bo'); d=c.user('ca')
    sp=c.call('al','POST','/api/spaces',{'name':'К','avatarColor':'sky'}); sid=sp['id']
    code=sp['inviteCode']
    c.call('bo','POST','/api/spaces/join',{'inviteCode':code}); c.call('ca','POST','/api/spaces/join',{'inviteCode':code})
    c.settle()
    full=c.call('al','GET',f'/api/spaces/{sid}')
    gen=[x for x in full['channels'] if x['type']=='text'][0]['id']
    voice=[x for x in full['channels'] if x['type']=='voice'][0]['id']
    cat0=full['categories'][0]['id']
    c.call('bo','GET',f'/api/spaces/{sid}/channels')
    c.call('bo','GET','/api/spaces/1/channels')
    c.call('bo','POST',f'/api/spaces/{sid}/channels',{'name':'x','type':'text'})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'   ','type':'text'})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'a','type':'video'})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'a','type':'text','topic':5})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'a','type':'text','topic':'x'*1025})
    c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'a','type':'text','categoryId':'nope'})
    ch=c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'  Мой  Канал\tТут ','type':'text','topic':' тема\r\nвторая  ','categoryId':cat0})
    cid=ch['id']
    ch2=c.call('al','POST',f'/api/spaces/{sid}/channels',{'name':'second','type':'voice'})
    c.call('bo','PATCH',f'/api/channels/{cid}',{'name':'x'})
    c.call('al','PATCH',f'/api/channels/nope',{'name':'x'})
    c.call('al','PATCH',f'/api/channels/{cid}',{})
    c.call('al','PATCH',f'/api/channels/{cid}',{'name':5})
    c.call('al','PATCH',f'/api/channels/{cid}',{'position':-1})
    c.call('al','PATCH',f'/api/channels/{cid}',{'position':'1'})
    c.call('al','PATCH',f'/api/channels/{cid}',{'name':'Новое Имя','topic':None,'position':7})
    c.call('al','PATCH',f'/api/channels/{cid}',{'categoryId':'nope'})
    c.call('al','PATCH',f'/api/channels/{cid}',{'categoryId':None})
    c.call('al','PATCH',f'/api/channels/{cid}',{'categoryId':cat0,'topic':''})
    # категории
    c.call('bo','POST',f'/api/spaces/{sid}/categories',{'name':'x'})
    c.call('al','POST',f'/api/spaces/{sid}/categories',{'name':'  '})
    c.call('al','POST',f'/api/spaces/{sid}/categories',{'name':'x'*101})
    cat=c.call('al','POST',f'/api/spaces/{sid}/categories',{'name':'  Тайное Место '})
    kid=cat['id']
    c.call('al','PATCH',f'/api/categories/{kid}',{})
    c.call('al','PATCH',f'/api/categories/{kid}',{'name':''})
    c.call('al','PATCH',f'/api/categories/{kid}',{'name':' Секрет ','position':9})
    c.call('bo','PATCH',f'/api/categories/{kid}',{'name':'x'})
    c.call('al','PATCH',f'/api/categories/nope',{'name':'x'})
    # переопределения
    c.call('bo','GET',f'/api/channels/{cid}/overrides')
    c.call('al','GET',f'/api/channels/{cid}/overrides')
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role'})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':'nope','deny':'2'})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'x'})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'2','version':''})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'2','version':'zzz'})
    o=c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'2','version':'none'})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'2','allow':'1024','version':'none'})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'role','targetId':sid,'deny':'2','allow':'1024','version':o.get('version')})
    c.call('al','PUT',f'/api/channels/{cid}/overrides',{'targetType':'member','targetId':b,'allow':'2'})
    c.call('al','GET',f'/api/channels/{cid}/overrides')
    c.settle()
    c.call('bo','GET',f'/api/spaces/{sid}')
    c.call('ca','GET',f'/api/spaces/{sid}')
    c.call('ca','GET',f'/api/spaces/{sid}/channels')
    c.call('ca','PATCH',f'/api/channels/{cid}',{'name':'x'})
    c.call('al','DELETE',f'/api/channels/{cid}/overrides/member/{b}?version=bad')
    c.call('al','DELETE',f'/api/channels/{cid}/overrides/member/{b}?version=')
    c.call('al','DELETE',f'/api/channels/{cid}/overrides/member/{b}')
    c.call('al','DELETE',f'/api/channels/{cid}/overrides/member/{b}')
    c.call('al','DELETE',f'/api/channels/{cid}/overrides/role/{sid}')
    # категория: приватность
    c.call('al','GET',f'/api/categories/{kid}/overrides')
    c.call('ca','GET',f'/api/categories/{kid}/overrides')
    c.call('al','PATCH',f'/api/channels/{cid}',{'categoryId':kid})
    c.call('al','PUT',f'/api/categories/{kid}/overrides',{'targetType':'role','targetId':sid,'deny':'2'})
    c.call('al','PUT',f'/api/categories/{kid}/overrides',{'targetType':'member','targetId':d,'allow':'2'})
    c.call('al','GET',f'/api/categories/{kid}/overrides')
    c.settle()
    c.call('bo','GET',f'/api/spaces/{sid}')
    c.call('ca','GET',f'/api/spaces/{sid}')
    c.call('al','DELETE',f'/api/categories/{kid}/overrides/member/{d}')
    # раскладка
    c.call('bo','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[],'categories':[]})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':1})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[{'id':'x','position':0,'categoryId':None}],'categories':[]})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[{'id':gen,'position':-2,'categoryId':None}],'categories':[]})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[{'id':gen,'position':2,'categoryId':'zz'}],'categories':[]})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[],'categories':[{'id':'zz','position':1}]})
    c.call('al','PATCH',f'/api/spaces/{sid}/channel-layout',{'channels':[{'id':gen,'position':3,'categoryId':kid},{'id':voice,'position':1,'categoryId':None}],'categories':[{'id':kid,'position':0},{'id':cat0,'position':5}]})
    c.settle()
    c.call('al','GET',f'/api/spaces/{sid}')
    c.call('bo','GET',f'/api/spaces/{sid}')
    # удаление
    c.call('bo','DELETE',f'/api/categories/{kid}')
    c.call('al','DELETE',f'/api/categories/{kid}')
    c.call('al','DELETE',f'/api/categories/{kid}')
    c.call('bo','DELETE',f'/api/channels/{cid}')
    c.call('al','DELETE',f'/api/channels/{cid}')
    c.call('al','DELETE',f'/api/channels/{cid}')
    c.call('al','GET',f'/api/spaces/{sid}')
if __name__=='__main__': sys.exit(1 if run(channels, show='-v' in sys.argv) else 0)
