    c.call('bo','PATCH',f"/api/messages/{m1['id']}",{'content':'  исправлено  '})
    c.settle()
    c.call('ca','DELETE',f"/api/messages/{m1['id']}")
    c.call('ca','DELETE','/api/messages/nope')
    # WS
    c.send('bo',{'type':'bogus'}); c.settle()
    c.send('bo',{'type':'message_create'}); c.settle()
    c.send('bo',{'type':'message_create','channelId':gen}); c.settle()
    c.send('bo',{'type':'message_create','channelId':gen,'content':'я'*4001}); c.settle()
    c.send('bo',{'type':'message_create','channelId':'nope','content':'x'}); c.settle()
    c.send('ev',{'type':'message_create','channelId':gen,'content':'x'}); c.settle()
    c.send('bo',{'type':'message_create','channelId':gen,'content':'@everyone'}); c.settle()
    c.send('bo',{'type':'message_create','channelId':gen,'content':'x','replyToId':'nope'}); c.settle()
    c.send('bo',{'type':'message_create','channelId':gen,'content':' по сокету ','replyToId':m2['id']}); c.settle()
