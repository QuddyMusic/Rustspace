    c.send('bo',{'type':'reaction_add','messageId':m2['id'],'emoji':'👍'}); c.settle()
    c.send('bo',{'type':'reaction_add','messageId':m2['id'],'emoji':'👍'}); c.settle()
    c.send('ca',{'type':'reaction_add','messageId':m2['id'],'emoji':'🎉'}); c.settle()
    c.call('ca','GET',f'/api/channels/{gen}/messages')
    c.send('bo',{'type':'reaction_remove','messageId':m2['id'],'emoji':'👍'}); c.settle()
    c.send('bo',{'type':'reaction_remove','messageId':m2['id'],'emoji':'👍'}); c.settle()
