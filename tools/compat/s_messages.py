    c.call('bo','PATCH',f"/api/messages/{m1['id']}",{})
    c.call('bo','PATCH',f"/api/messages/{m1['id']}",{'content':'я'*4001})
    c.call('bo','PATCH',f"/api/messages/{m1['id']}",{'content':'теперь @everyone'})
