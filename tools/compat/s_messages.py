    c.call('ca','GET',f"/api/channels/{gen}/messages?after={m1['id']}")
    c.call('ca','GET',f"/api/channels/{gen}/messages?after={m1['id']}&before={m3['id']}")
    c.call('ca','GET',f"/api/channels/{gen}/messages?after=1&after=2")
