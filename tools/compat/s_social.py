import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from scn import run
def social(c):
    a=c.user('al'); b=c.user('bo'); d=c.user('ca'); e=c.user('ev')
    c.call('al','GET','/api/social/friends'); c.call('al','GET','/api/social/requests')
    c.call('al','POST','/api/social/requests',{})
    c.call('al','POST','/api/social/requests',{'username':'nobody'+c.tag})
    c.call('al','POST','/api/social/requests',{'username':'al'+c.tag})
    c.call('al','POST','/api/social/requests',{'homeUserId':'','homeInstance':'x'})
    r=c.call('al','POST','/api/social/requests',{'username':'  BO'+c.tag.upper()+' '}); c.settle()
    c.call('al','POST','/api/social/requests',{'username':'bo'+c.tag})
    c.call('bo','POST','/api/social/requests',{'username':'al'+c.tag})
    c.call('al','GET','/api/social/requests'); c.call('bo','GET','/api/social/requests')
    rid=r['requestId']
    c.call('al','PATCH',f'/api/social/requests/{rid}',{'status':'accepted'})
    c.call('bo','PATCH',f'/api/social/requests/{rid}',{'status':'maybe'})
    c.call('bo','PATCH','/api/social/requests/nope',{'status':'accepted'})
    c.call('bo','PATCH',f'/api/social/requests/{rid}',{'status':'accepted'}); c.settle()
    c.call('al','GET','/api/social/friends'); c.call('bo','GET','/api/social/friends')
    c.call('al','POST','/api/social/requests',{'username':'bo'+c.tag})
    r2=c.call('al','POST','/api/social/requests',{'username':'ca'+c.tag}); c.settle()
    c.call('ca','DELETE',f"/api/social/requests/{r2['requestId']}")
    c.call('ca','PATCH',f"/api/social/requests/{r2['requestId']}",{'status':'declined'}); c.settle()
    c.call('al','DELETE',f"/api/social/requests/{r2['requestId']}")
    r3=c.call('al','POST','/api/social/requests',{'username':'ev'+c.tag}); c.settle()
    c.call('al','DELETE',f"/api/social/requests/{r3['requestId']}"); c.settle()
    c.call('al','DELETE','/api/social/requests/nope')
    r4=c.call('ca','POST','/api/social/requests',{'username':'al'+c.tag}); c.settle()
    c.call('al','PATCH',f"/api/social/requests/{r4['requestId']}",{'status':'accepted'}); c.settle()
    c.call('al','GET',f'/api/users/{b}/mutuals'); c.call('bo','GET',f'/api/users/{d}/mutuals')
    c.call('ev','GET','/api/social/search'); c.call('ev','GET','/api/social/search?q='+c.tag)
    c.call('al','GET','/api/social/discover?q='+c.tag+'&limit=3&offset=0')
    c.call('bo','GET','/api/social/discover?q='+c.tag+'&limit=abc')
    # группы
    g=c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':d}]}); c.settle(); gid=g['id']
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':e}]})
    c.call('bo','PATCH',f'/api/dm/{gid}',{'name':'x'})
    c.call('al','PATCH',f'/api/dm/{gid}',{})
    c.call('al','PATCH',f'/api/dm/{gid}',{'name':5})
    c.call('al','PATCH',f'/api/dm/{gid}',{'name':'я'*51})
    c.call('al','PATCH',f'/api/dm/{gid}',{'icon':'a/b'})
    c.call('al','PATCH',f'/api/dm/{gid}',{'icon':'nofile.png'})
    c.call('al','PATCH',f'/api/dm/{gid}',{'name':'  Группа  '}); c.settle()
    c.call('al','PATCH',f'/api/dm/{gid}',{'name':'Группа'})
    c.call('al','PATCH',f'/api/dm/{gid}',{'name':None}); c.settle()
    c.call('bo','POST',f'/api/dm/{gid}/messages',{'content':'в группу'}); c.settle()
    c.call('bo','POST',f'/api/dm/{gid}/members',{'userId':e})
    c.call('bo','POST',f'/api/dm/{gid}/members',{'userId':d})
    c.call('bo','POST',f'/api/dm/{gid}/transfer',{'newOwnerId':b})
    c.call('al','POST',f'/api/dm/{gid}/transfer',{'newOwnerId':a})
    c.call('al','POST',f'/api/dm/{gid}/transfer',{'newOwnerId':e})
    c.call('al','POST',f'/api/dm/{gid}/transfer',{'newOwnerId':'nope'})
    c.call('bo','DELETE',f'/api/dm/{gid}/members/{d}')
    c.call('al','DELETE',f'/api/dm/{gid}/members/{a}')
    c.call('al','DELETE',f'/api/dm/{gid}/members/{e}')
    c.call('al','DELETE',f'/api/dm/{gid}/members/{d}'); c.settle()
    c.call('al','POST',f'/api/dm/{gid}/members',{'userId':d}); c.settle()
    c.call('al','POST',f'/api/dm/{gid}/transfer',{'newOwnerId':b}); c.settle()
    c.call('bo','DELETE',f'/api/dm/{gid}/members'); c.settle()
    c.call('al','GET',f'/api/dm/{gid}/messages')
    c.call('al','GET','/api/dm')
    c.call('ca','DELETE',f'/api/dm/{gid}/members'); c.settle()
    c.call('al','DELETE',f'/api/dm/{gid}/members'); c.settle()
    c.call('al','GET','/api/dm')
    # приглашение в пространство
    sp=c.call('al','POST','/api/spaces',{'name':'С','avatarColor':'sky','description':'оп'})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':sp['id'],'inviteCode':'bad','target':{'userId':b}})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':sp['id'],'inviteCode':sp['inviteCode'],'target':{'userId':e}})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':sp['id'],'inviteCode':sp['inviteCode'],'target':{'userId':a}})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':sp['id'],'inviteCode':sp['inviteCode'],'target':{}})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':sp['id'],'inviteCode':sp['inviteCode'],'target':{'userId':b}}); c.settle()
    # разрыв дружбы
    c.call('al','DELETE',f'/api/social/friends/{e}')
    c.call('al','DELETE',f'/api/social/friends/{b}'); c.settle()
    c.call('bo','GET','/api/social/friends')
if __name__=='__main__': sys.exit(1 if run(social, show='-v' in sys.argv) else 0)
