import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from scn import run
def spaces(c):
    a=c.user('al'); b=c.user('bo'); d=c.user('ca')
    c.call('al','POST','/api/spaces',{})
    c.call('al','POST','/api/spaces',{'name':'   '})
    c.call('al','POST','/api/spaces',{'name':'x'*101})
    sp=c.call('al','POST','/api/spaces',{'name':' Дом ','description':'  опис  ','visibility':'bogus','avatarColor':'mint'})
    sid=sp['id']
    c.call('al','GET','/api/spaces')
    c.call('al','GET',f'/api/spaces/{sid}')
    c.call('bo','GET',f'/api/spaces/{sid}')
    c.call('bo','GET','/api/spaces/999')
    c.call('bo','POST',f'/api/spaces/{sid}/invite')
    inv=c.call('al','POST',f'/api/spaces/{sid}/invite')
    code=inv['inviteCode']
    c.call(None,'GET',f'/api/spaces/invite/{code}/preview',label='preview')
    c.call(None,'GET','/api/spaces/invite/nope/preview',label='preview-missing')
    c.call('bo','POST','/api/spaces/join',{})
    c.call('bo','POST','/api/spaces/join',{'inviteCode':'nope'})
    c.call('bo','POST','/api/spaces/join',{'inviteCode':code})
    c.call('bo','POST','/api/spaces/join',{'inviteCode':code})
    c.call('ca','POST',f'/api/spaces/{sid}/join',{'inviteCode':'bad'})
    c.call('ca','POST',f'/api/spaces/{sid}/join',{'inviteCode':code})
    c.settle()
    c.call('bo','GET',f'/api/spaces/{sid}/members')
    # настройки
    c.call('bo','PATCH',f'/api/spaces/{sid}',{'name':'Хак'})
    c.call('al','PATCH',f'/api/spaces/{sid}',{})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'name':'Дом 2','description':'','avatarColor':'nope'})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'name':'Дом 2','description':' новое ','avatarColor':'sky','visibility':'public','directoryListed':True,'ownerTitle':' Царь '})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'directoryListed':'yes'})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'visibility':'private'})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'directoryListed':True})
    c.call('al','PATCH',f'/api/spaces/{sid}',{'ownerTitle':''})
    c.call('bo','PATCH',f'/api/spaces/{sid}',{'ownerTitle':'x'})
    # роли
    c.call('bo','POST',f'/api/spaces/{sid}/roles',{'name':'r'})
    r1=c.call('al','POST',f'/api/spaces/{sid}/roles',{'name':' Мод ','color':'#ff0000','permissions':'2060'})
    c.call('al','POST',f'/api/spaces/{sid}/roles',{'name':'мод'})
    c.call('al','POST',f'/api/spaces/{sid}/roles',{'name':'MOD','permissions':'abc'})
    r2=c.call('al','POST',f'/api/spaces/{sid}/roles',{})
    r3=c.call('al','POST',f'/api/spaces/{sid}/roles',{'name':'Третья','permissions':'0'})
    c.call('al','GET',f'/api/spaces/{sid}')
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{'position':3})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r3['id']}",{'above':r1['id']})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r3['id']}",{'below':sid})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r3['id']}",{'above':sid})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{sid}",{'position':2})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{'permissions':'2062','permissionsVersion':'bad'})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{'name':'new role'})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{'name':' Модератор ','color':'#00ff00','permissions':'2062'})
    c.call('al','PATCH',f"/api/spaces/{sid}/roles/nope",{'name':'x'})
    c.call('al','GET',f'/api/spaces/{sid}')
    # роли участников
    c.call('al','POST',f"/api/spaces/{sid}/members/{b}/roles",{})
    c.call('al','POST',f"/api/spaces/{sid}/members/{b}/roles",{'roleId':sid})
    c.call('al','POST',f"/api/spaces/{sid}/members/{a}/roles",{'roleId':r1['id']})
    c.call('al','POST',f"/api/spaces/{sid}/members/{b}/roles",{'roleId':r1['id']})
    c.call('al','POST',f"/api/spaces/{sid}/members/{b}/roles",{'roleId':r1['id']})
    c.call('bo','GET',f'/api/spaces/{sid}')
    c.call('ca','GET',f'/api/spaces/{sid}')
    # бо — модератор с MANAGE_ROLES(8)+MANAGE_CHANNELS(4)+VIEW(2)+SEND(1024)+... иерархия
    c.call('bo','POST',f"/api/spaces/{sid}/members/{d}/roles",{'roleId':r1['id']})
    c.call('bo','POST',f"/api/spaces/{sid}/members/{d}/roles",{'roleId':r2['id']})
    c.call('bo','POST',f'/api/spaces/{sid}/roles',{'name':'Выше','permissions':'128'})
    c.call('bo','POST',f'/api/spaces/{sid}/roles',{'name':'Ниже','permissions':'2'})
    c.call('bo','PATCH',f"/api/spaces/{sid}/roles/{r1['id']}",{'name':'моя'})
    c.call('bo','DELETE',f"/api/spaces/{sid}/roles/{r1['id']}")
    c.call('bo','PATCH',f"/api/spaces/{sid}/members/{d}",{'roleIds':[r2['id']]})
    c.call('bo','PATCH',f"/api/spaces/{sid}/members/{d}",{'roleIds':[r2['id'],r2['id']]})
    c.call('bo','PATCH',f"/api/spaces/{sid}/members/{d}",{'roleIds':'x'})
    c.call('bo','PATCH',f"/api/spaces/{sid}/members/{d}",{})
    c.call('bo','PATCH',f"/api/spaces/{sid}/members/{d}",{'nickname':'Кэрол'})
    c.call('ca','PATCH',f"/api/spaces/{sid}/members/{d}",{'nickname':'  Сама  '})
    c.call('ca','PATCH',f"/api/spaces/{sid}/members/{d}",{'nickname':'a\nb'})
    c.call('ca','PATCH',f"/api/spaces/{sid}/members/{d}",{'nickname':None})
    c.call('al','PATCH',f"/api/spaces/{sid}/members/{d}",{'nickname':'От владельца','roleIds':[r3['id']]})
    c.call('al','PATCH',f"/api/spaces/{sid}/members/nope",{'nickname':'x'})
    c.call('al','DELETE',f"/api/spaces/{sid}/members/{d}/roles/{r3['id']}")
    c.call('al','DELETE',f"/api/spaces/{sid}/roles/{sid}")
    c.call('al','DELETE',f"/api/spaces/{sid}/roles/{r2['id']}")
    c.call('al','GET',f'/api/spaces/{sid}')
    # исключение, бан
    c.call('ca','DELETE',f"/api/spaces/{sid}/members/{b}")
    c.call('al','DELETE',f"/api/spaces/{sid}/members/{a}")
    c.call('bo','DELETE',f"/api/spaces/{sid}/members/{a}")
    c.call('ca','DELETE',f"/api/spaces/{sid}/members/{d}")
    c.call('ca','DELETE',f"/api/spaces/{sid}/members/{d}")
    c.call('ca','POST','/api/spaces/join',{'inviteCode':code})
    c.call('ca','GET',f'/api/spaces/{sid}/bans')
    c.call('al','POST',f'/api/spaces/{sid}/bans',{})
    c.call('al','POST',f'/api/spaces/{sid}/bans',{'userId':a})
    c.call('al','POST',f'/api/spaces/{sid}/bans',{'userId':d,'reason':'  спам  '})
    c.stop('ca')  # оригинал продолжает слать забаненному события пространства; мы — нет
    c.call('al','POST',f'/api/spaces/{sid}/bans',{'userId':d})
    c.call('al','GET',f'/api/spaces/{sid}/bans')
    c.call('ca','POST','/api/spaces/join',{'inviteCode':code})
    c.call('al','DELETE',f'/api/spaces/{sid}/bans/{d}')
    c.call('al','DELETE',f'/api/spaces/{sid}/bans/{d}')
    # владение
    c.call('bo','PATCH',f'/api/spaces/{sid}/transfer-ownership',{'newOwnerId':b})
    c.call('al','PATCH',f'/api/spaces/{sid}/transfer-ownership',{})
    c.call('al','PATCH',f'/api/spaces/{sid}/transfer-ownership',{'newOwnerId':a})
    c.call('al','PATCH',f'/api/spaces/{sid}/transfer-ownership',{'newOwnerId':d})
    c.call('al','PATCH',f'/api/spaces/{sid}/transfer-ownership',{'newOwnerId':b})
    c.call('al','DELETE',f'/api/spaces/{sid}')
    c.call('bo','DELETE',f'/api/spaces/{sid}')
    c.call('bo','GET','/api/spaces')
if __name__=='__main__': sys.exit(1 if run(spaces, show='-v' in sys.argv) else 0)
