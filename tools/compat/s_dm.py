import sys; sys.path.insert(0,'/tmp/stand')
from scn import run
def dm(c):
    a=c.user('al'); b=c.user('bo'); d=c.user('ca')
    c.call('al','GET','/api/dm')
    c.call('al','POST','/api/dm',{})
    c.call('al','POST','/api/dm',{'userId':'nope'})
    c.call('al','POST','/api/dm',{'userId':a})
    ch=c.call('al','POST','/api/dm',{'userId':b}); did=ch['id']
    c.call('al','POST','/api/dm',{'userId':b})
    c.call('bo','GET','/api/dm')
    c.call('ca','GET',f'/api/dm/{did}/messages')
    c.call('ca','POST',f'/api/dm/{did}/messages',{'content':'x'})
    c.call('al','POST',f'/api/dm/{did}/messages',{})
    c.call('al','POST',f'/api/dm/{did}/messages',{'content':5})
    c.call('al','POST',f'/api/dm/{did}/messages',{'content':'я'*4001})
    c.call('al','POST',f'/api/dm/{did}/messages',{'content':'x','replyToId':'nope'})
    c.call('al','POST',f'/api/dm/{did}/messages',{'content':'x','attachments':['nope']})
    m1=c.call('al','POST',f'/api/dm/{did}/messages',{'content':'  привет  '}); c.settle()
    m2=c.call('bo','POST',f'/api/dm/{did}/messages',{'content':'ответ','replyToId':m1['id']}); c.settle()
    c.call('bo','GET','/api/dm')
    c.call('bo','GET',f'/api/dm/{did}/messages')
    c.call('bo','GET',f"/api/dm/{did}/messages?after={m1['id']}")
    c.call('bo','GET',f"/api/dm/{did}/messages?before={m2['id']}&limit=5")
    c.call('bo','PATCH',f"/api/dm/messages/{m1['id']}",{'content':'чужое'})
    c.call('al','PATCH',f"/api/dm/messages/{m1['id']}",{})
    c.call('al','PATCH',f"/api/dm/messages/{m1['id']}",{'content':' правка '}); c.settle()
    c.call('ca','PATCH',f"/api/dm/messages/{m1['id']}",{'content':'x'})
    c.call('al','PATCH','/api/dm/messages/nope',{'content':'x'})
    c.send('al',{'type':'dm_message_create'}); c.settle()
    c.send('ca',{'type':'dm_message_create','dmChannelId':did,'content':'x'}); c.settle()
    c.send('al',{'type':'dm_message_create','dmChannelId':did,'content':'  '}); c.settle()
    c.send('al',{'type':'dm_message_create','dmChannelId':did,'content':' по сокету '}); c.settle()
    c.send('al',{'type':'dm_typing_start','dmChannelId':did}); c.settle()
    c.send('ca',{'type':'dm_typing_start','dmChannelId':did}); c.settle()
    c.send('bo',{'type':'reaction_add','messageId':m1['id'],'emoji':'👍'}); c.settle()
    c.send('bo',{'type':'reaction_add','messageId':m1['id'],'emoji':'👍'}); c.settle()
    c.send('ca',{'type':'reaction_add','messageId':m1['id'],'emoji':'👍'}); c.settle()
    c.call('al','GET',f'/api/dm/{did}/messages')
    c.send('bo',{'type':'reaction_remove','messageId':m1['id'],'emoji':'👍'}); c.settle()
    c.send('bo',{'type':'dm_message_edit','messageId':m1['id'],'content':'x'}); c.settle()
    c.send('bo',{'type':'dm_message_edit','messageId':m2['id'],'content':' сокет-правка '}); c.settle()
    c.send('bo',{'type':'channel_ack','channelId':did,'messageId':m1['id']}); c.settle()
    c.send('bo',{'type':'mark_unread','channelId':did,'messageId':'0'}); c.settle()
    c.send('al',{'type':'dm_message_delete','messageId':m2['id']}); c.settle()
    c.send('bo',{'type':'dm_message_delete','messageId':m2['id']}); c.settle()
    c.send('bo',{'type':'dm_message_delete'}); c.settle()
    c.call('bo','DELETE',f"/api/dm/messages/{m1['id']}")
    c.call('al','DELETE',f"/api/dm/messages/{m1['id']}"); c.settle()
    c.call('al','DELETE','/api/dm/messages/nope')
    # закрытие и повторное открытие
    c.call('ca','DELETE',f'/api/dm/{did}')
    c.call('bo','DELETE',f'/api/dm/{did}'); c.settle()
    c.call('bo','GET','/api/dm')
    c.call('al','POST',f'/api/dm/{did}/messages',{'content':'вернись'}); c.settle()
    c.call('bo','GET','/api/dm')
    # группы: ошибки
    c.call('al','POST','/api/dm/group',{})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':'nope'}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':b}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':a}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':b},{'id':d}]})
    c.call('al','POST','/api/dm/group',{'users':[{'id':str(i)} for i in range(10)]})
    c.call('al','PATCH',f'/api/dm/{did}',{'name':'x'})
    c.call('al','PATCH','/api/dm/nope',{'name':'x'})
    c.call('al','POST',f'/api/dm/{did}/members',{'userId':d})
    c.call('al','POST',f'/api/dm/{did}/members',{})
    c.call('al','DELETE',f'/api/dm/{did}/members')
    c.call('al','DELETE',f'/api/dm/{did}/members/{b}')
    c.call('al','POST',f'/api/dm/{did}/transfer',{})
    c.call('al','POST',f'/api/dm/{did}/transfer',{'newOwnerId':b})
    c.call('al','POST','/api/dm/space-invite',{})
    c.call('al','POST','/api/dm/space-invite',{'spaceId':'1','inviteCode':'x','target':{'userId':b}})
if __name__=='__main__': sys.exit(1 if run(dm, show='-v' in sys.argv) else 0)
